/**
 * Get translation for a key in the specified language
 * Falls back to English if key not found in target language
 */
export function t(key, language = 'en') {
  const langTranslations = translations[language] || translations.en
  const value = langTranslations[key]
  
  if (value) return value
  
  // Fallback to English
  return translations.en[key] || key
}

/**
 * Get all available languages
 */
export function getAvailableLanguages() {
  return Object.entries(LANGUAGES).map(([code, info]) => ({
    code,
    ...info
  }))
}

/**
 * Hook for using translations in components
 */
export function useTranslation(language = 'en') {
  return {
    t: (key) => t(key, language),
    language,
    languageInfo: LANGUAGES[language] || LANGUAGES.en,
    availableLanguages: getAvailableLanguages(),
  }
}
